/**
 * Chat export as Markdown — portable, readable in any editor, and a good fit for the
 * Obsidian workflows this app already supports. Keeping the builder pure means the
 * format is testable without touching the DOM.
 */
import type { Chat } from '../types'

/** Which assistant label to print in the transcript. */
export interface ExportOptions {
  /** App name shown in the header and next to assistant turns. */
  assistantName?: string
  /** User-facing labels, localized by the caller. */
  userLabel?: string
  /** Injected for tests; defaults to the chat's own timestamps. */
  now?: number
}

/** `2026-10-23 14:05` in local time; stable and sortable enough for a transcript. */
export function formatExportDate(timestamp: number): string {
  const date = new Date(timestamp)
  if (Number.isNaN(date.getTime())) return ''
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}`
}

/** A filesystem-safe `.md` filename derived from the chat title. */
export function exportFileName(title: string): string {
  const slug = title
    .trim()
    .toLowerCase()
    .replace(/[\\/:*?"<>|]+/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/^\.+/, '')
    .slice(0, 60)
  return `${slug || 'chat'}.md`
}

/**
 * Render one chat as a Markdown document.
 *
 * Message bodies are emitted verbatim: they are already Markdown, and escaping them
 * would damage code blocks. Only the role headings are generated by us.
 */
export function buildChatMarkdown(chat: Chat, options: ExportOptions = {}): string {
  const assistantName = options.assistantName ?? 'Kora'
  const userLabel = options.userLabel ?? 'You'
  const now = options.now ?? Date.now()

  const lines: string[] = [
    `# ${chat.title || 'Chat'}`,
    '',
    `*${formatExportDate(chat.createdAt)}${chat.updatedAt !== chat.createdAt ? ` → ${formatExportDate(chat.updatedAt)}` : ''}*`,
    '',
  ]

  for (const message of chat.messages) {
    const label =
      message.role === 'user' ? userLabel : message.role === 'assistant' ? assistantName : 'System'
    lines.push(`## ${label}${message.timestamp ? ` · ${formatExportDate(message.timestamp)}` : ''}`, '')
    lines.push(message.content.trim() || '_(empty)_', '')
  }

  lines.push('---', `_Exported from ${assistantName} · ${formatExportDate(now)}_`, '')
  return lines.join('\n')
}
